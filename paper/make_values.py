#!/usr/bin/env python3
"""Write paper/values.tex, the \\V{key} numbers of main_clean.tex, from results/*.csv.

    python3 paper/make_values.py

Every results file written by the notebook has the columns key,value,unit,note, and each row becomes one
\\V{key}. The literature census has one row per year, and its totals and its last year become the
census-* keys. No number in the manuscript is typed by hand: a key that does not exist prints in red.
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUTPUT = ROOT / "paper" / "values.tex"


def notebook_values(path):
    with open(path, newline="") as handle:
        for row in csv.DictReader(handle):
            yield row["key"], row["value"]


def census_values(path):
    years, totals, run = [], None, None
    for line in path.read_text().splitlines():
        if line.startswith("#total,"):
            totals = line.split(",")[1:]
        elif line.startswith("#run,"):
            run = line.split(",")[1]
        elif line[:1].isdigit():
            years.append(line.split(","))
    names = ["all", "title", "learned", "review"]
    for name, total in zip(names, totals):
        yield f"census-total-{name}", total
    last = years[-1]
    yield "census-first-year", years[0][0]
    yield "census-last-year", last[0]
    for name, count in zip(names, last[1:]):
        yield f"census-last-{name}", count
    yield "census-run", run


def main():
    values = {}
    for path in sorted(RESULTS.glob("*.csv")):
        rows = census_values(path) if path.name == "literature_census.csv" else notebook_values(path)
        for key, value in rows:
            if key in values:
                raise SystemExit(f"{path.name}: the key {key} is already defined")
            values[key] = value
    lines = ["% Generated by paper/make_values.py from results/*.csv. Do not edit."]
    lines += [f"\\expandafter\\def\\csname v@{key}\\endcsname{{{value}}}" for key, value in sorted(values.items())]
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"{len(values)} values written to paper/values.tex")


if __name__ == "__main__":
    main()
