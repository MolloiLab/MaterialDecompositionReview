#!/usr/bin/env python3
"""Rebuild the reference list of paper/main_clean.tex from LITERATURE.md, in order of first citation.

    python3 paper/make_references.py

The list between the BEGIN REFERENCES and END REFERENCES lines of main_clean.tex is the only generated
part of that file. Every \\cite key of the manuscript must have a verified \\bibitem in LITERATURE.md.
A key that has none stops the script, so no reference reaches the paper without a verified record.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAPER = ROOT / "paper" / "main_clean.tex"
LITERATURE = ROOT / "LITERATURE.md"
BEGIN = "% BEGIN REFERENCES (generated by make_references.py from LITERATURE.md, do not edit)"
END = "% END REFERENCES"


def verified_entries():
    text = LITERATURE.read_text()
    entries = {}
    for match in re.finditer(r"\\bibitem\{([^}]+)\}\n(.*?)(?=\n\n|\n```)", text, re.S):
        entries[match.group(1)] = match.group(2).strip()
    return entries


def cited_keys(body):
    keys = []
    uncommented = "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in body.splitlines())
    for match in re.finditer(r"\\cite\{([^}]+)\}", uncommented):
        for key in (k.strip() for k in match.group(1).split(",")):
            if key not in keys:
                keys.append(key)
    return keys


def main():
    text = PAPER.read_text()
    start, stop = text.index(BEGIN), text.index(END)
    keys = cited_keys(text[:start])
    entries = verified_entries()
    missing = [key for key in keys if key not in entries]
    if missing:
        raise SystemExit("No verified entry in LITERATURE.md for: " + ", ".join(missing))
    items = "\n\n".join(f"\\bibitem{{{key}}}\n{entries[key]}" for key in keys)
    block = f"{BEGIN}\n\\begin{{thebibliography}}{{99}}\n\n{items}\n\n\\end{{thebibliography}}\n"
    PAPER.write_text(text[:start] + block + text[stop:])
    print(f"{len(keys)} references, in order of first citation")


if __name__ == "__main__":
    main()
